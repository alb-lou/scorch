#include "../Source/Dsp.h"
#include <cstdio>
#include <fstream>
using namespace sat;

static double goertzel (const std::vector<float>& x, double f, double fs)
{
    const double w = 2 * kPi * f / fs; double re = 0, im = 0;
    for (size_t n = 0; n < x.size(); ++n) { re += x[n] * std::cos (w * (double) n); im += x[n] * std::sin (w * (double) n); }
    return 2.0 * std::sqrt (re * re + im * im) / (double) x.size();
}

int main()
{
    const double fs = 192000;
    const char* names[] = { "TapeTube", "Console", "Germanium", "Triode", "Pentode" };
    std::printf ("Harmonics of a 1 kHz sine at -12 dBFS (dB rel. fundamental), H2..H5, plus DC and peak\n");
    for (int st = 0; st < NumStyles; ++st)
        for (double drive : { 0.0, 3.0, 6.0, 10.0 })
        {
            StyleCore c; c.prepare (fs);
            const int len = (int) fs; std::vector<float> y ((size_t) len);
            const double g = dbToLin (driveToDb (drive, false)) * dbToLin (-12);
            double pk = 0, dc = 0;
            for (int i = 0; i < len; ++i)
            {
                y[(size_t) i] = c.process (st, (float) (g * std::sin (2 * kPi * 1000.0 * i / fs)));
                if (! std::isfinite (y[(size_t) i])) { std::printf ("NaN!\n"); return 1; }
                if (i > len / 2) { pk = std::max (pk, (double) std::fabs (y[(size_t) i])); dc += y[(size_t) i]; }
            }
            const double h1 = goertzel (y, 1000, fs);
            std::printf ("%-10s drive %4.1f | H1 %6.1f dB |", names[st], drive, linToDb (h1));
            for (int h = 2; h <= 5; ++h) std::printf (" H%d %6.1f", h, linToDb (goertzel (y, 1000.0 * h, fs) / h1));
            std::printf (" | DC %.4f peak %.2f\n", dc / (len / 2), pk);
        }

    // stability: full-scale square, max drive + punish
    for (int st = 0; st < NumStyles; ++st)
    {
        StyleCore c; c.prepare (fs); double pk = 0;
        for (int i = 0; i < (int) fs; ++i)
            pk = std::max (pk, (double) std::fabs (c.process (st, ((i / 96) & 1 ? 1.f : -1.f) * (float) dbToLin (55))));
        std::printf ("%-10s max-drive square peak out: %.2f\n", names[st], pk);
    }

    auto lut = computeAutoGainLut (fs);
    std::printf ("\nAuto-gain LUT (dB), punish off, drive 0/2/4/6/8/10:\n");
    for (int st = 0; st < NumStyles; ++st)
    {
        std::printf ("%-10s", names[st]);
        for (int d : { 0, 4, 8, 12, 16, 20 }) std::printf (" %6.2f", lut[(size_t) ((st * 2) * kLutDrivePoints + d)]);
        std::printf ("\n");
    }

    std::ofstream h ("../Source/AutoGainLut.h");
    h << "// Generated by tests/dsp_test.cpp - static auto-gain compensation (dB).\n"
         "// Reference: pink noise at -18 dBFS RMS. Index [style][punish][drive*2].\n#pragma once\nnamespace sat {\n"
         "inline constexpr float kAutoGainLut[5][2][21] = {\n";
    for (int st = 0; st < NumStyles; ++st)
    {
        h << " {";
        for (int p = 0; p < 2; ++p)
        {
            h << "{";
            for (int d = 0; d < kLutDrivePoints; ++d) h << lut[(size_t) ((st * 2 + p) * kLutDrivePoints + d)] << "f" << (d < 20 ? "," : "");
            h << "}" << (p < 1 ? "," : "");
        }
        h << "}" << (st < 4 ? "," : "") << "\n";
    }
    h << "};\n}\n";
    return 0;
}
